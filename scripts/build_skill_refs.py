"""
Builds the generated references of the dobby skills plugin.

Two kinds of files under plugins/dobby/skills/*/references/:

* Generated from code: the MCP tool reference (from vision_mcp/server.py, read
  with ast so no desktop backend starts) and each app plugin's feature catalog.
* Copied from the repo's own notes (learnings/, docs/) so the plugin is
  self-contained when Claude Code copies it into its plugin cache.

Every file starts with a header naming its source. Edit the source, then run:

    python scripts/build_skill_refs.py          # write
    python scripts/build_skill_refs.py --check  # exit 1 if anything is stale (CI / tests)
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path
from typing import Dict, List

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / "plugins" / "dobby" / "skills"

# skill -> [(reference file name, source path relative to ROOT)]
COPIED: Dict[str, List[tuple]] = {
    "perception": [
        ("zero-token-element-discovery.md", "learnings/zero_token_element_discovery.md"),
        ("visual-delta-verification.md", "learnings/visual_delta_verification.md"),
        ("architecture.md", "docs/architecture.md"),
    ],
    "app-chrome": [
        ("browser-recipes.md", "learnings/browser_interaction_recipes.md"),
        ("gemini-web-clipboard.md", "learnings/gemini_web_clipboard_extraction_recipe.md"),
    ],
    "app-vivado": [
        ("waveform-automation.md", "learnings/vivado_gui_waveform_automation.md"),
        ("layout-for-dv.md", "learnings/vivado_ui_layout_customization_for_dv.md"),
        ("plugin.md", "docs/plugins/vivado.md"),
        ("tool-features-research.md", "research/vivado_tool_features_and_ai_automation.md"),
    ],
    "app-verdi": [
        ("eda-ui-automation.md", "learnings/verdi_and_complex_eda_ui_automation.md"),
        ("tool-features-research.md", "research/verdi_tool_features_and_ai_automation.md"),
    ],
    "troubleshoot": [
        ("setup.md", "docs/setup.md"),
        ("linux-window-management.md", "learnings/linux_desktop_window_management.md"),
    ],
}

HEADER = "<!-- GENERATED by scripts/build_skill_refs.py from {src}. Edit the source, then rerun. -->\n\n"


def _literal_dict(tree: ast.Module, name: str) -> dict:
    for node in tree.body:
        targets = []
        if isinstance(node, ast.Assign):
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
            value = node.value
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            targets = [node.target.id]
            value = node.value
        if name in targets:
            return ast.literal_eval(value)
    return {}


def _is_tool(fn: ast.FunctionDef) -> bool:
    for d in fn.decorator_list:
        target = d.func if isinstance(d, ast.Call) else d
        if isinstance(target, ast.Attribute) and target.attr == "tool":
            return True
    return False


def _summary(doc: str) -> str:
    lines = []
    for line in (doc or "").strip().splitlines():
        if not line.strip():
            break
        lines.append(line.strip())
    return " ".join(lines)


def _params(fn: ast.FunctionDef) -> str:
    args = fn.args.args
    defaults = [None] * (len(args) - len(fn.args.defaults)) + list(fn.args.defaults)
    out = []
    for a, d in zip(args, defaults):
        s = a.arg
        if d is not None:
            s += "=" + ast.unparse(d)
        out.append(f"`{s}`")
    return ", ".join(out) or "none"


def tools_reference() -> str:
    src = ROOT / "vision_mcp" / "server.py"
    tree = ast.parse(src.read_text(encoding="utf-8"))
    domains = _literal_dict(tree, "_TOOL_DOMAINS")
    tools = [n for n in tree.body if isinstance(n, ast.FunctionDef) and _is_tool(n)]
    by_domain: Dict[str, List[ast.FunctionDef]] = {}
    for fn in tools:
        domain = domains.get(fn.name, ("unregistered", ""))[0]
        by_domain.setdefault(domain, []).append(fn)
    order = ["core", "window_mgmt", "developer", "advanced_vision", "vdom", "skills", "plugins", "unregistered"]
    out = [HEADER.format(src="vision_mcp/server.py"), "# dobby MCP tools\n\n",
           f"{len(tools)} tools. Only `core` is on by default; enable others with "
           "`manage_toolsets(action=\"enable\", domains=[...])`.\n"]
    for domain in sorted(by_domain, key=lambda d: order.index(d) if d in order else len(order)):
        out.append(f"\n## {domain}\n\n| Tool | Parameters | What it does |\n| --- | --- | --- |\n")
        for fn in by_domain[domain]:
            summary = _summary(ast.get_docstring(fn) or "").replace("|", "\\|")
            out.append(f"| `{fn.name}` | {_params(fn).replace('|', chr(92) + '|')} | {summary} |\n")
    return "".join(out)


def features_reference(app_id: str) -> str:
    sys.path.insert(0, str(ROOT))
    from vision_mcp.plugins.registry import PluginRegistry  # noqa: WPS433

    plugin = PluginRegistry().get(app_id)
    out = [HEADER.format(src=f"vision_mcp/plugins/{app_id}.py"),
           f"# {plugin.name}: features\n\n",
           f"Run with `invoke_plugin_feature(feature_id, plugin_id=\"{app_id}\", args={{...}})`. "
           "Prefer these over clicking: they use hotkeys and menus the plugin already knows.\n\n",
           "| Feature | What it does | Hotkey | Menu | Pane | Parameters |\n| --- | --- | --- | --- | --- | --- |\n"]
    for f in plugin.list_features():
        menu = " > ".join(f.menu_path) if f.menu_path else ""
        params = ", ".join(f"`{k}`" for k in (f.parameters or {}))
        desc = f.description.replace("|", "\\|")
        out.append(f"| `{f.feature_id}` | {desc} | {f.hotkey or ''} | {menu} | {f.target_pane or ''} | {params} |\n")
    panes = sorted(getattr(plugin, "sub_panes", {}) or {})
    if panes:
        out.append("\nNamed panes for `capture_pane(pane_name)`: " + ", ".join(f"`{p}`" for p in panes) + ".\n")
    return "".join(out)


def expected_files() -> Dict[Path, str]:
    files: Dict[Path, str] = {
        SKILLS / "perception" / "references" / "tools.md": tools_reference(),
        SKILLS / "app-chrome" / "references" / "features.md": features_reference("chrome"),
        SKILLS / "app-vivado" / "references" / "features.md": features_reference("vivado"),
    }
    for skill, pairs in COPIED.items():
        for name, rel in pairs:
            text = (ROOT / rel).read_text(encoding="utf-8")
            files[SKILLS / skill / "references" / name] = HEADER.format(src=rel) + text
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated reference is stale")
    args = ap.parse_args()
    stale = []
    for path, content in expected_files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path.relative_to(ROOT))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    if args.check and stale:
        print("Stale skill references (run python scripts/build_skill_refs.py):")
        for p in stale:
            print(f"  {p}")
        return 1
    print(f"{'checked' if args.check else 'wrote'} {len(expected_files())} references, {len(stale)} {'stale' if args.check else 'updated'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
